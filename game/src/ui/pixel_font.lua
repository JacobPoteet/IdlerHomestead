-- Every glyph, in the order the image strip holds them.
local ORDER = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?'-+/%$()·=><"
  .. '"#&*@[\\]^_`{|}~×°→…'
PixelFont.HEIGHT = 9 -- font pixels per line of glyphs: 7 of caps and 2 of descenders
PixelFont.CAP = 7 -- cap height in font pixels

local font

--- The ImageFont, one font pixel per texel, nearest filtered; built on first use.
function PixelFont.get()
  if font then
    return font
  end
  local chars = {}
  for _, code in utf8.codes(ORDER) do
    chars[#chars + 1] = utf8.char(code)
  end
  local width = 1
  for _, ch in ipairs(chars) do
    width = width + #G[ch][1] + 1
  end
  local data = love.image.newImageData(width, PixelFont.HEIGHT)
  local x = 0
  local function separator()
    for y = 0, PixelFont.HEIGHT - 1 do
      data:setPixel(x, y, 1, 0, 1, 1)
    end
    x = x + 1
  end
  separator()
  for _, ch in ipairs(chars) do
    local rows = G[ch]
    local w = #rows[1]
    for y = 1, PixelFont.HEIGHT do
      local row = rows[y]
      for c = 1, w do
        if row and row:sub(c, c) == "#" then
          data:setPixel(x + c - 1, y - 1, 1, 1, 1, 1)
        end
      end
    end
    x = x + w
    separator()
  end
  font = love.graphics.newImageFont(data, table.concat(chars), 1)
  font:setFilter("nearest", "nearest")
  return font
end

--- The glyph rows of a character (tests and tools), or nil.
function PixelFont.glyph(ch)
  return G[ch]
end

return PixelFont
