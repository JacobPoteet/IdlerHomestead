#!/usr/bin/env bash
# Writes game/src/core/version_stamp.lua (gitignored) so a packaged build knows its tag and commit
# (D91, #225). The release workflow runs this before packaging; devs may run it by hand.
#   tools/stamp_version.sh [tag]     tag defaults to the nearest tag reachable from HEAD
#   tools/stamp_version.sh --clear   delete the stamp (source runs then read .git directly)
set -u
cd "$(dirname "$0")/.." || exit 1
out=game/src/core/version_stamp.lua
if [ "${1:-}" = "--clear" ]; then
  rm -f "$out"
  exit 0
fi
hash=$(git rev-parse --short=7 HEAD 2>/dev/null || echo "")
tag="${1:-}"
ahead=0
if [ -z "$tag" ]; then
  tag=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
  if [ -n "$tag" ]; then
    ahead=$(git rev-list --count "$tag"..HEAD 2>/dev/null || echo 0)
  fi
fi
dirty=false
if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
  dirty=true
fi
cat > "$out" <<LUA
-- Generated by tools/stamp_version.sh. Do not edit or commit.
return { tag = "$tag", hash = "$hash", ahead = $ahead, dirty = $dirty }
LUA
echo "Stamped $out: ${tag:-dev} $hash"
